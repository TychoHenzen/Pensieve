if len(VOCAB) < 256:
    raise RuntimeError(f"VOCAB must hold at least 256 words, has {len(VOCAB)}")


def sample(source: random.Random, n: int) -> list[str]:
    """Draw `n` distinct words from `VOCAB` using `source`.

    Raises `ValueError` if `n` exceeds the size of `VOCAB`, so a caller
    never silently receives fewer words than it asked for.
    """
    if n > len(VOCAB):
        raise ValueError(f"cannot draw {n} distinct words from a vocabulary of {len(VOCAB)}")
    if n < 0:
        raise ValueError(f"n must be non-negative, got {n}")
    return source.sample(VOCAB, n)


def chance_rate(n_choices: int) -> float:
    """Return the chance accuracy of guessing one word out of `n_choices` options.

    A caller passes `len(VOCAB)` for the full vocabulary, or a smaller
    count for a generator that limits its draw to a known subset, so
    chance accuracy stays a known number on paper either way.
    """
    if n_choices <= 0:
        raise ValueError(f"n_choices must be positive, got {n_choices}")
    return 1.0 / n_choices
